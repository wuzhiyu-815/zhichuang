"""Agent 之间传递的统一消息格式。"""

import time
import uuid


def 创建消息(发送者, 接收者, 任务类型, 项目编号="", 数据=None, 状态="待处理",
             镜头编号=None, 关联消息=None):
    return {
        "消息编号": uuid.uuid4().hex[:16],
        "创建时间": time.time(),
        "发送者": str(发送者),
        "接收者": str(接收者),
        "任务类型": str(任务类型),
        "项目编号": str(项目编号 or ""),
        "镜头编号": 镜头编号,
        "状态": str(状态),
        "关联消息": 关联消息,
        "数据": 数据 or {},
    }
