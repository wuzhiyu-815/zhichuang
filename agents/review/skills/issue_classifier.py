"""把审片结果归类为可执行的修复方向。"""

from core.skill_result import 技能结果


问题关键词 = {
    "角色一致性": ("脸", "人脸", "角色", "发型", "服装", "身份", "串脸", "融脸"),
    "动作连续性": ("静帧", "幻灯片", "动作", "运动", "僵硬", "慢动作"),
    "构图运镜": ("构图", "景别", "机位", "运镜", "镜头", "主体不清"),
    "场景连续性": ("场景", "背景", "环境", "跳变", "空间"),
    "物体细节": ("手", "手指", "肢体", "物体", "道具", "畸变", "变形"),
    "台词匹配": ("台词", "对白", "说话", "口型", "声音"),
}


def 分类审片问题(上下文, 参数):
    审片 = 参数.get("审片") or {}
    原始问题 = 审片.get("problems") or []
    if isinstance(原始问题, str):
        原始问题 = [原始问题]
    分类 = []
    for 问题 in 原始问题:
        文本 = str(问题)
        命中 = [类别 for 类别, 关键词 in 问题关键词.items()
                if any(词 in 文本 for 词 in 关键词)]
        分类.extend(命中 or ["综合质量"])
    分类 = list(dict.fromkeys(分类))
    return 技能结果(True, 数据={"问题": list(map(str, 原始问题)), "分类": 分类})
