"""根据审片结果决定是否重制以及如何修复。"""

from core.skill_result import 技能结果
from agents.review.skills.issue_classifier import 分类审片问题


修复模板 = {
    "角色一致性": "锁定人物脸型、发型、年龄和体型，禁止串脸；服装遵循本镜 wardrobe，同一场连续戏保持连续，跨时间或活动合理换装。不得以角色一致性为由改回参考图服装。",
    "动作连续性": "强化现实速度的连续动作：首帧即动作进行中，动作有明确起点、过程和结果，禁止静帧、幻灯片感和无理由慢动作。",
    "构图运镜": "明确主体位置、景别、机位和镜头运动，保持主体清晰，运镜服务动作，不让镜头运动遮挡关键动作。",
    "场景连续性": "锁定同一场景的空间布局、时间、光线、色调和关键陈设，镜头内不得无理由跳变背景。",
    "物体细节": "强化手部、肢体和道具的数量、连接关系与运动轨迹，避免手指、肢体和道具畸变。",
    "台词匹配": "让说话人、口型、动作和台词时序严格对应，台词必须在对应人物开口时出现。",
    "综合质量": "保持画面主体明确、动作连贯、现实速度和电影化写实质感，减少无关视觉变化。",
}


class 优化智能体:
    名称 = "优化智能体"

    def 评估(self, 审片, 阈值=72, 当前次数=0, 最大次数=1):
        分类结果 = 分类审片问题(None, {"审片": 审片})
        分类 = 分类结果.数据.get("分类", [])
        try:
            分数 = int(float(审片.get("score", 0)))
        except (TypeError, ValueError):
            分数 = 0
        是否需要优化 = 分数 < int(阈值) and 当前次数 < int(最大次数)
        修复约束 = [修复模板[类别] for 类别 in 分类 if 类别 in 修复模板]
        原有约束 = str(审片.get("fix_prompt_addendum") or "").strip()
        if 原有约束 and 原有约束 not in 修复约束:
            修复约束.insert(0, 原有约束)
        动作 = "自动重制" if 是否需要优化 else ("接受当前版本" if 分数 >= int(阈值) else "转人工处理")
        return 技能结果(True, 数据={
            "分数": 分数,
            "阈值": int(阈值),
            "当前次数": int(当前次数),
            "最大次数": int(最大次数),
            "分类": 分类,
            "动作": 动作,
            "需要优化": 是否需要优化,
            "修复约束": "\n".join(修复约束),
        })


优化智能体 = 优化智能体()
